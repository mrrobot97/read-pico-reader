"""Generate and verify the built-in Sudoku puzzles."""

import argparse
import random
import re
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[1] / 'main/apps/sudoku_puzzles.inc'
COUNT = 12
DIGITS = set(range(1, 10))
ROWS = [tuple(range(i, i + 9)) for i in range(0, 81, 9)]
COLS = [tuple(range(i, 81, 9)) for i in range(9)]
BOXES = [tuple(r * 9 + c for r in range(y, y + 3) for c in range(x, x + 3))
         for y in (0, 3, 6) for x in (0, 3, 6)]
UNITS = ROWS + COLS + BOXES
PEERS = [set().union(*(unit for unit in UNITS if cell in unit)) - {cell} for cell in range(81)]


def solve(grid, limit=2, rng=None):
    board = list(grid)
    solutions = []

    def visit():
        cell, choices = -1, DIGITS
        for i, digit in enumerate(board):
            if digit:
                continue
            remaining = DIGITS - {board[j] for j in PEERS[i]}
            if not remaining:
                return
            if cell < 0 or len(remaining) < len(choices):
                cell, choices = i, remaining
                if len(choices) == 1:
                    break
        if cell < 0:
            solutions.append(tuple(board))
            return
        digits = sorted(choices)
        if rng is not None:
            rng.shuffle(digits)
        for digit in digits:
            board[cell] = digit
            visit()
            if len(solutions) == limit:
                break
        board[cell] = 0

    visit()
    return solutions


def grade(grid):
    """0: naked singles, 1: also hidden singles, 2: beyond singles."""
    board = list(grid)
    level = 0
    while not all(board):
        candidates = {i: DIGITS - {board[j] for j in PEERS[i]}
                      for i, digit in enumerate(board) if not digit}
        single = next(((i, min(values)) for i, values in candidates.items() if len(values) == 1), None)
        if single is not None:
            board[single[0]] = single[1]
            continue
        level = 1
        for unit in UNITS:
            for digit in sorted(DIGITS - {board[i] for i in unit}):
                cells = [i for i in unit if digit in candidates.get(i, ())]
                if len(cells) == 1:
                    single = cells[0], digit
                    break
            if single is not None:
                break
        if single is None:
            return 2
        board[single[0]] = single[1]
    return level


def generate():
    rng = random.Random(20261111)
    for level, clues in enumerate((39, 33, 29)):
        batch = []
        for _ in range(500):
            answer, = solve([0] * 81, limit=1, rng=rng)
            grid = list(answer)
            order = list(range(81))
            rng.shuffle(order)
            remaining = 81
            for cell in order:
                grid[cell] = 0
                if len(solve(grid)) == 1:
                    remaining -= 1
                    if remaining == clues:
                        break
                else:
                    grid[cell] = answer[cell]
            if remaining == clues and grade(grid) == level:
                batch.append((grid, answer))
                if len(batch) == COUNT:
                    break
        if len(batch) != COUNT:
            raise RuntimeError(f'Could not generate difficulty {level}')
        yield batch


def verify():
    entries = re.findall(r'\{"([0-9]{81})", "([1-9]{81})"\}', OUTPUT.read_text())
    assert len(entries) == COUNT * 3
    assert len({grid for grid, _ in entries}) == len(entries)
    for i, (grid, answer) in enumerate(entries):
        puzzle, solution = tuple(map(int, grid)), tuple(map(int, answer))
        assert all({solution[cell] for cell in unit} == DIGITS for unit in UNITS)
        assert all(given in (0, correct) for given, correct in zip(puzzle, solution))
        assert solve(puzzle) == [solution], i
        assert grade(puzzle) == i // COUNT, i
    print(f'{len(entries)} puzzles verified with unique solutions and graded difficulty')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify the checked-in bank without rewriting it')
    if not parser.parse_args().check:
        lines = ['/* SPDX-License-Identifier: Apache-2.0 */',
                 '/* Generated by tools/gen_sudoku_puzzles.py. Keep existing indices stable. */']
        for batch in generate():
            lines.append('{')
            for grid, solution in batch:
                given = ''.join(map(str, grid))
                answer = ''.join(map(str, solution))
                lines.append(f'    {{"{given}", "{answer}"}},')
            lines.append('},')
        OUTPUT.write_text('\n'.join(lines) + '\n')
    verify()


if __name__ == '__main__':
    main()
